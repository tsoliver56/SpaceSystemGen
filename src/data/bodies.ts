/** Compressed radial scale: true ordering preserved, inner system kept legible. */
export function orbitRadius(au: number, sunR: number, maxR: number): number {
  const inner = sunR + maxR * 0.16;
  return inner + (maxR - inner) * Math.pow(au / MAX_AU, 0.42);
}

export function fmtKm(n: number): string {
  return `${n.toLocaleString("en-US")} km`;
}

export function fmtSim(days: number): string {
  const y = Math.floor(days / 365.25);
  const d = Math.floor(days - y * 365.25);
  return `T+${y}y ${String(d).padStart(3, "0")}d`;
}
